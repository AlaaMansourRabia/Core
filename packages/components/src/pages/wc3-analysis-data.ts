/* ------------------------------------------------------------------- types */

/** The seven stages of the analysis rail, in pipeline order. */
export type Wc3AnalysisStageId = "source" | "filter" | "traverse" | "derive" | "group" | "viz" | "publish";

/** Object analysis walks the ontology; data analysis walks governed datasets. */
export type Wc3AnalysisMode = "object" | "data";

/** Grouping dimension offered by the Group stage. */
export type Wc3AnalysisGroupBy = "contractor" | "severity" | "zone";

/** Time grain layered on top of the grouping dimension. */
export type Wc3AnalysisGrain = "month" | null;

/** Rendering offered by the Visualize stage. */
export type Wc3AnalysisViz = "bar" | "table";

/** The three execution engines a spec can route to. */
export type Wc3AnalysisRouteId = "operational" | "analytical" | "runtime";

/** One stage of the rail. */
export type Wc3AnalysisStage = {id: Wc3AnalysisStageId; label: string};

/** One row of `ot_worker` — the traversal/join target of every analysis on this page. */
export type Wc3WorkerRow = {
	worker_id: string;
	full_name: string;
	trade: string;
	employer: string;
	contractor: string;
	badge_id: string;
	crew_id: string | null;
	last_seen_at: string;
	risk_score: number;
	current_zone_id: string | null;
	shift: string;
	induction_date: string;
};

/** One row of `ot_zone` — backs the `zone_registry` dataset and the zone grouping. */
export type Wc3ZoneRow = {
	zone_id: string;
	zone_name: string;
	zone_kind: string;
	capacity_limit: number;
	risk_score: number;
	geo_location: string;
	site_id: string;
	storey_id: string | null;
};

/** One row of `ot_activity` — backs the `schedule_activities_p6` dataset. */
export type Wc3ActivityRow = {
	activity_id: string;
	activity_name: string;
	wbs_code: string;
	planned_start: string;
	planned_finish: string;
	baseline_start: string;
	baseline_finish: string;
	duration_days: number;
	percent_complete: number;
	critical_path: boolean;
	zone_id: string;
	project_id: string;
	cost_code: string;
	pred_activity_id: string | null;
	delay_days: number;
	budget_sar: number;
	earned_value_sar: number;
	contractor: string;
};

/** Any row the analysis engine can scan, read generically by field name. */
export type Wc3AnalysisRow = Record<string, string | number | boolean | null>;

/** A scanned row after the traversal/join attached its worker (null when the key is unlinked). */
export type Wc3AnalysisJoinedRow = Wc3AnalysisRow & {__worker: Wc3WorkerRow | null};

/**
 * A metric definition. `needs` names the dataset the metric requires; when that dataset has
 * no materialised rows the metric is unsupported and `compute` is null — the page must name
 * the missing input instead of producing a number.
 */
export type Wc3AnalysisMetric = {
	id: string;
	label: string;
	needs: string | null;
	compute: ((rows: Wc3AnalysisJoinedRow[]) => number | null) | null;
};

/** A bounded predicate evaluated before traversal. */
export type Wc3AnalysisFilter = {field: string; value: string};

/** The semantic query. One spec, three possible execution engines. */
export type Wc3AnalysisSpec = {
	mode: Wc3AnalysisMode;
	/** Object mode: the ontology object type the set starts from. */
	sourceType?: string;
	/** Data mode: the catalogue dataset the set starts from. */
	sourceDs?: string;
	filters: Wc3AnalysisFilter[];
	/** Object mode: the property the traversal follows to `ot_worker`. */
	traverse?: string | null;
	/** Data mode: the catalogue dataset joined in. */
	joinDs?: string | null;
	metrics: string[];
	groupBy: Wc3AnalysisGroupBy | null;
	grain: Wc3AnalysisGrain;
	/** Weeks back from the fixture clock; 0 means current state only. */
	window: number;
	viz: Wc3AnalysisViz;
	name: string;
};

/** A saved analysis — the spec, the execution route and the lineage kept together. */
export type Wc3SavedAnalysis = {
	id: string;
	name: string;
	spec: Wc3AnalysisSpec;
	route: string;
	rows: number;
	groups: number;
	ms: number;
	at: string;
};

/** A saved analytical result. */
export type Wc3Materialisation = {id: string; name: string; groups: number; at: string; route: string};

