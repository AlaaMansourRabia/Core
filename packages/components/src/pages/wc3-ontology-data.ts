const OT_BY_ID = new Map(WC3_OBJECT_TYPES.map((o) => [o.id, o]));
const IF_BY_ID = new Map(WC3_INTERFACES.map((i) => [i.id, i]));
const GROUP_BY_ID = new Map(WC3_TYPE_GROUPS.map((g) => [g.id, g]));

export const getObjectType = (id: string) => OT_BY_ID.get(id);
export const getInterface = (id: string) => IF_BY_ID.get(id);
export const getTypeGroup = (id: string) => GROUP_BY_ID.get(id);
export const instanceCount = (otId: string) => WC3_INSTANCE_COUNTS[otId] ?? 0;
