export const WC3_ANALYSIS_SOURCE_DATASET_IDS: string[] = [
	"ds_observations",
	"ds_workers",
	"ds_activities",
	"ds_badge_import",
];

/** The observation rows, typed — the object-mode source set. Reused, never re-declared. */
export const WC3_OBSERVATION_ROWS: Wc3ObservationRow[] = WC3_PROCESS_INSTANCES.ot_observation;

const WORKER_BY_ID = new Map(WC3_WORKER_ROWS.map((w) => [w.worker_id, w]));

/** The worker behind a foreign key, or null when the key does not resolve. */
export const analysisWorker = (workerId: string | null | undefined): Wc3WorkerRow | null =>
	(workerId ? WORKER_BY_ID.get(workerId) : undefined) ?? null;

/**
 * Rows behind a catalogue dataset. A dataset declared in the catalogue but not materialised
 * in this fixture returns an empty array — that emptiness is the honest answer, not a gap.
 */
export function analysisDatasetRows(dsId: string): Wc3AnalysisRow[] {
	if (dsId === "ds_observations") return WC3_OBSERVATION_ROWS as unknown as Wc3AnalysisRow[];
	if (dsId === "ds_workers") return WC3_WORKER_ROWS as unknown as Wc3AnalysisRow[];
	if (dsId === "ds_zones") return WC3_ZONE_ROWS as unknown as Wc3AnalysisRow[];
	if (dsId === "ds_activities") return WC3_ACTIVITY_ROWS as unknown as Wc3AnalysisRow[];
	return [];
}

/** The catalogue entry for a dataset id. */
export const analysisDataset = (dsId: string): Wc3CatalogSource | undefined =>
	WC3_DATASOURCE_CATALOG.find((c) => c.id === dsId);

/** Display name for a dataset id, falling back to the id when it is not in the catalogue. */
export const analysisDatasetName = (dsId: string): string => analysisDataset(dsId)?.name ?? dsId;

/** True when the dataset holds materialised rows in this fixture. */
export const analysisDatasetMaterialised = (dsId: string): boolean => analysisDatasetRows(dsId).length > 0;

/* ----------------------------------------------------------------- metrics */

const HOUR_MS = 3_600_000;

const parseStamp = (s: string): number => Date.parse(s.replace(" ", "T"));

/**
 * Metric catalogue, verbatim from the prototype's `AN_METRICS`. `compute` is null exactly
 * when `needs` names a dataset with no materialised rows — the metric is then unsupported
 * and the page must name the missing input rather than show a value.
 */
export const WC3_ANALYSIS_METRICS: Wc3AnalysisMetric[] = [
	{id: "obs_count", label: "Observation count", needs: null, compute: (rows) => rows.length},
	{
		id: "distinct_w",
		label: "Distinct workers",
		needs: null,
		compute: (rows) => new Set(rows.map((r) => r.__worker?.worker_id).filter(Boolean)).size,
	},
	{
		id: "critical",
		label: "Critical + High",
		needs: null,
		compute: (rows) => rows.filter((r) => r.severity_level === "Critical" || r.severity_level === "High").length,
	},
	{
		id: "median_close",
		label: "Median hours to close",
		needs: null,
		compute: (rows) => {
			const hours = rows
				.filter((r) => typeof r.closed_at === "string" && typeof r.observed_at === "string")
				.map((r) => (parseStamp(r.closed_at as string) - parseStamp(r.observed_at as string)) / HOUR_MS)
				.sort((a, b) => a - b);
			const median = hours[Math.floor(hours.length / 2)];
			return median === undefined ? null : Math.round(median);
		},
	},
	{id: "exposure_h", label: "Exposure hours", needs: "ds_badge_import", compute: null},
	{id: "incident_rate", label: "Incident rate / 1k h", needs: "ds_badge_import", compute: null},
];

/** The metric definition for an id. */
export const analysisMetric = (id: string): Wc3AnalysisMetric | undefined =>
	WC3_ANALYSIS_METRICS.find((m) => m.id === id);

/** The dataset a metric needs but that holds no rows, or null when the metric is computable. */
export const analysisMetricMissingInput = (m: Wc3AnalysisMetric): string | null =>
	m.needs && !analysisDatasetMaterialised(m.needs) ? m.needs : null;

