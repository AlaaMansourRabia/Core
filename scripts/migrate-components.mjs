#!/usr/bin/env node
// A1 migration scaffold — turn hand-authored library-index component entries into artifact-manifest/0.2
// component manifests (the source of truth). Structural fields (path/import/variants/sizes) stay owned
// by the code; this only migrates the SEMANTIC knowledge.
//
//   node scripts/migrate-components.mjs Button Input Select ...
//
// It writes manifests/<id>.component.json for each named component and does NOT touch library-index.json
// (run `node scripts/project-catalog-manifests.mjs` afterwards to regenerate the catalog projection).
//
// Conversions (per A1-DECISION-RECORD): requires -> requiredProviders; avoid[] -> commonMistakes[] with
// `avoidOverride` preserving the exact catalog line (so the projection is byte-stable); knowledgeLevel
// dropped (generated from completeness); adds version + lineage.

import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const index = JSON.parse(readFileSync(join(repoRoot, "library-index.json"), "utf8"));

const ORDER = [
	"schemaVersion",
	"id",
	"tier",
	"name",
	"category",
	"version",
	"manifestStatus",
	"source",
	"tags",
	"subcomponents",
	"intent",
	"when",
	"whenNot",
	"chooseOver",
	"insteadUse",
	"pairsWith",
	"requiredProviders",
	"commonMistakes",
	"variantIntent",
	"lineage",
];

function findEntry(name) {
	for (const [bucket, list] of Object.entries(index.components)) {
		const e = list.find((x) => x.name === name);
		if (e) return {bucket, e};
	}
	return null;
}

// avoid line -> structured commonMistakes entry. avoidOverride preserves the exact catalog text so the
// projection stays byte-stable; mistake/fix are derived from two common WakeCap phrasings:
//   1. "<misuse> — <fix>"            (em-dash split)
//   2. "Use <Component> for <why>"    (this-instead pattern: the named component is the correct choice)
// Lines matching neither get a placeholder fix and should be hand-refined.
function toCommonMistakes(name, avoid) {
	return (avoid ?? []).map((a) => {
		const i = a.indexOf(" — ");
		if (i >= 0) {
			const p1 = a.slice(0, i).trim();
			const p2 = a.slice(i + 3).trim();
			return {
				mistake: p1.replace(/^Use\b/, `Using ${name}`),
				fix: p2.charAt(0).toUpperCase() + p2.slice(1),
				avoidOverride: a,
			};
		}
		const useFor = a.match(/^Use ([A-Z][A-Za-z]+(?:\/[A-Z][A-Za-z]+)*) (for|when|as|inside) (.+)$/);
		if (useFor) {
			return {mistake: `Using ${name} ${useFor[2]} ${useFor[3]}`, fix: `Use ${useFor[1]}`, avoidOverride: a};
		}
		return {mistake: a, fix: "See chooseOver for the correct alternative.", avoidOverride: a};
	});
}

const names = process.argv.slice(2);
if (!names.length) {
	console.error("usage: node scripts/migrate-components.mjs <ComponentName> [...]");
	process.exit(1);
}

let written = 0;
const skipped = [];
for (const name of names) {
	const hit = findEntry(name);
	if (!hit) {
		console.error(`  ✗ ${name}: not found in library-index.json`);
		process.exit(1);
	}
	const {bucket, e} = hit;
	if (e.tier !== "component") {
		skipped.push(`${name} (tier=${e.tier}, not a component)`);
		continue;
	}
	if (e.manifest) {
		skipped.push(`${name} (already manifested: ${e.manifest})`);
		continue;
	}
	const id = e.import.replace("@wakecap/core-ui/", "");
	const m = {
		schemaVersion: "artifact-manifest/0.2",
		id,
		tier: "component",
		name: e.name,
		category: bucket,
		version: "1.0.0",
		manifestStatus: "complete",
		source: {path: e.path, import: e.import, export: e.name},
		tags: e.tags ?? [],
	};
	if (e.subcomponents) m.subcomponents = e.subcomponents;
	m.intent = e.intent;
	m.when = e.when ?? [];
	if (e.whenNot) m.whenNot = e.whenNot;
	m.chooseOver = e.chooseOver ?? [];
	if (e.insteadUse) m.insteadUse = e.insteadUse;
	m.pairsWith = e.pairsWith ?? [];
	m.requiredProviders = e.requires ?? []; // requires -> requiredProviders
	const cm = toCommonMistakes(e.name, e.avoid);
	if (cm.length) m.commonMistakes = cm;
	if (e.variantIntent) m.variantIntent = e.variantIntent;
	m.lineage = {
		origin: "migrated",
		authoredBy: "A1 component migration batch (2026-07)",
		derivedFrom: {source: e.path, extracted: ["cva variants/sizes remain generated by the structural extractor"]},
		status: "accepted",
		verifiedBy: null,
		confidence: "unset — projection round-trip verified; no held-out eval yet",
		supersedes: null,
		lastValidated: "2026-07-05",
		notes: ["migrated from library-index.json (hand-authored catalog entry)"],
	};
	const out = {};
	for (const k of ORDER) if (k in m) out[k] = m[k];
	writeFileSync(join(repoRoot, "manifests", `${id}.component.json`), JSON.stringify(out, null, "\t") + "\n");
	written++;
	console.log(
		`  ✓ manifests/${id}.component.json  (avoid->commonMistakes: ${cm.length}, requiredProviders: ${m.requiredProviders.length})`,
	);
}
console.log(`\nwrote ${written} manifest(s); skipped ${skipped.length}.`);
for (const s of skipped) console.log(`  skip: ${s}`);
console.log(`\nNext: node scripts/project-catalog-manifests.mjs && pnpm validate:manifests`);
