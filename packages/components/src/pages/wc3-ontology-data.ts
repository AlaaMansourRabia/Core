/** Object types that implement an interface, directly or through an extended one. */
export function interfaceImplementors(ifaceId: string): Wc3ObjectType[] {
	const chain = (id: string): string[] => {
		const it = IF_BY_ID.get(id);
		return it ? [id, ...it.extends.flatMap(chain)] : [id];
	};
	return WC3_OBJECT_TYPES.filter((o) => o.implements.some((im) => chain(im.interfaceId).includes(ifaceId)));
}

/** Every property an interface promises, including those inherited from extended interfaces. */
export function interfaceAllProperties(iface: Wc3Interface): Wc3Interface["properties"] {
	const seen = new Set<string>();
	const out: Wc3Interface["properties"] = [];
	const walk = (it: Wc3Interface | undefined) => {
		if (!it) return;
		it.extends.forEach((id) => walk(IF_BY_ID.get(id)));
		it.properties.forEach((p) => {
			if (seen.has(p.apiName)) return;
			seen.add(p.apiName);
			out.push(p);
		});
	};
	walk(iface);
	return out;
}

/** Object types that consume a shared property. */
export function sharedPropertyConsumers(spId: string): Wc3ObjectType[] {
	return WC3_OBJECT_TYPES.filter((o) => o.properties.some((p) => p.sharedPropertyId === spId));
}

